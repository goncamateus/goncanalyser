"""Single-window Qt front end: video on the right, sectioned controls on the left.

Why this exists next to `steam-tune`: HighGUI has no section headers, so that tuner
spreads its knobs over four windows you drag apart by hand, and it has no file dialog
and nowhere to put the generic image controls. Qt has all of it, and a real thread --
decoding never blocks the widgets.

Nothing here is duplicated. `Config` and the whole plume pipeline come from `plume`,
the frame cache is `tune.Clip`, and the Steam-Tune sliders are generated by looping
over `tune.KNOBS` -- the same table that builds the HighGUI trackbars. One knob table,
one cache, two front ends.

Transport is the same as `steam-tune`: space plays and pauses, `.` and `,` step, and
the seek bar under the video jumps anywhere in the clip. Seeking is why the worker
uses `Clip` rather than reading the file straight through -- `Clip` caches raw frames
and per-frame temporal statistics, so stepping around re-uses the neighbours the
previous frame already decoded and aligned.

Processing order, one chain per displayed frame:

    frame from Clip (already cropped and scaled)
        -> contours (optional)  ------------> the region the plume pipeline may use
        -> plume pipeline (optional), its masks cut down to that region
        -> brightness / contrast / saturation / gamma
        -> plume outlines, then contour outlines
        -> background subtraction (optional)
        -> colour space view

Contours and the plume pipeline both read the frame before the adjustment sliders
touch it: every threshold in the plume pipeline is a percentile of the temperature
index, and a gamma or contrast change would move the exact percentiles a calibration
was tuned against. The adjustment sliders are for your eyes, not for the segmentation.

With the contour section on, the plume pipeline is confined to the pixels the contours
enclose -- everything outside is dropped from the masks, and a source that vents
outside the contours disappears from the count. The percentile thresholds are still
taken over the whole frame, for the same reason `plume_mask`'s own `roi` argument
takes them over the whole frame: a region that is mostly plume would push its own
p_hi through the roof and then find nothing.
"""

